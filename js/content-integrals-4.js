/* Чертеж за несобствен интеграл int_1^oo 1/x^p dx: лицето от 1 до b и границата му. */
function intImproperPlot(p, limitText) {
  var expr = '1/x^' + (p < 1 ? '(' + p + ')' : p);
  return {
    xmin: -0.6, xmax: 12.5, ymin: -0.25, ymax: 1.3, height: 240,
    params: [{ name: 'b', label: '`b`', min: 1, max: 40, step: 1, value: 4 }],
    curves: [{ expr: expr, color: 'blue', label: '`f(x) = 1/x^' + (p === 0.5 ? '(1/2)' : p === 1.5 ? '(3/2)' : p) + '`', domain: [0.4, 12.5] }],
    custom: intShadeUnder(expr, 1, 'b', {
      bounds: ['1', 'b'],
      readout: function (i) {
        return ['<b>b = ' + intNum(i.b, 0) + '</b>', 'лице от 1 до b <b>' + intNum(i.total, 3) + '</b>', limitText];
      }
    })
  };
}

